// Dependency-free, so the page's fake voice and the spec's speech route serve the same bytes.

/** Seconds of silence per spoken line: long enough that a line is still playing when a test looks. */
const lineSeconds = 4;
const sampleRate = 8000;

/** A mono 16-bit PCM WAV of silence. */
export function silentWav(seconds = lineSeconds): Uint8Array {
  const samples = seconds * sampleRate;
  const bytes = new Uint8Array(44 + samples * 2);
  const view = new DataView(bytes.buffer);
  const text = (offset: number, value: string) => {
    for (let index = 0; index < value.length; index++) {
      view.setUint8(offset + index, value.charCodeAt(index));
    }
  };
  text(0, 'RIFF');
  view.setUint32(4, 36 + samples * 2, true);
  text(8, 'WAVE');
  text(12, 'fmt ');
  view.setUint32(16, 16, true);
  view.setUint16(20, 1, true);
  view.setUint16(22, 1, true);
  view.setUint32(24, sampleRate, true);
  view.setUint32(28, sampleRate * 2, true);
  view.setUint16(32, 2, true);
  view.setUint16(34, 16, true);
  text(36, 'data');
  view.setUint32(40, samples * 2, true);
  return bytes;
}
