// Builds the desktop loader into `dist-electron/loader/`: the HTML, CSS and script from `src/loader/`, the colour and
// type tokens generated from the web's `apps/web/src/styles.css` (the one source of the palette), the fonts the
// loader paints with, and `window-backgrounds.json`, the canvas colour per theme the main process gives the window.
// Run after `vite build`, which empties `dist-electron`. Imports `@isagi/shared/css-tokens` (TypeScript), so it runs
// under `tsx`.
import { cpSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  customPropertiesAt,
  indexAfter,
  isagiDarkRootBlock,
  isagiThemeBlocks,
  stripCssComments,
} from '@isagi/shared/css-tokens';

const desktopRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const webRoot = resolve(desktopRoot, '../web');
const source = resolve(desktopRoot, 'src/loader');
const output = resolve(desktopRoot, 'dist-electron/loader');

/** The fonts styles.css imports, from the same packages the web bundles (and electron-builder takes licenses from). */
const fontPackages = ['sora', 'source-sans-3', 'fira-code'];

export function loaderTokens(stylesCss) {
  const css = stripCssComments(stylesCss);
  const dark = new Map([
    ...customPropertiesAt(css, indexAfter(css, isagiThemeBlocks.dark)),
    ...customPropertiesAt(css, indexAfter(css, isagiDarkRootBlock)),
  ]);
  const light = customPropertiesAt(css, indexAfter(css, isagiThemeBlocks.light));
  const block = (selector, tokens) =>
    `${selector} {\n${[...tokens].map(([name, value]) => `  ${name}: ${value};`).join('\n')}\n}\n`;
  const tokensCss =
    '/* Generated by apps/desktop/scripts/build-loader.mjs from apps/web/src/styles.css. Do not edit. */\n' +
    block(':root', dark) +
    block(":root[data-theme='light']", light);
  const backgrounds = { dark: dark.get('--color-canvas'), light: light.get('--color-canvas') };
  for (const [theme, color] of Object.entries(backgrounds)) {
    if (!/^#[0-9a-f]{6}$/iu.test(color ?? '')) {
      throw new Error(`styles.css --color-canvas for ${theme} is not a #rrggbb literal: ${color}`);
    }
  }
  return { tokensCss, backgrounds };
}

function build() {
  const { tokensCss, backgrounds } = loaderTokens(
    readFileSync(resolve(webRoot, 'src/styles.css'), 'utf8'),
  );
  mkdirSync(output, { recursive: true });
  for (const file of ['loader.html', 'loader.css', 'loader.js']) {
    cpSync(resolve(source, file), resolve(output, file));
  }
  writeFileSync(resolve(output, 'tokens.css'), tokensCss);
  writeFileSync(
    resolve(output, 'window-backgrounds.json'),
    `${JSON.stringify(backgrounds, null, 2)}\n`,
  );
  for (const name of fontPackages) {
    const fontRoot = resolve(webRoot, 'node_modules/@fontsource-variable', name);
    const target = resolve(output, 'fonts', name);
    mkdirSync(target, { recursive: true });
    cpSync(resolve(fontRoot, 'index.css'), resolve(target, 'index.css'));
    cpSync(resolve(fontRoot, 'files'), resolve(target, 'files'), { recursive: true });
  }
  console.log(`loader built in ${output}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) build();
